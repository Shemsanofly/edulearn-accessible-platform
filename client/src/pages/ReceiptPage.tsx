import { useQuery } from '@tanstack/react-query';
import { ArrowLeft, GraduationCap, Printer } from 'lucide-react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import type { Receipt } from '../../../shared/types';
import { Button, CardSkeleton, ErrorState } from '../components/ui';
import { api } from '../lib/api';
import { useUser } from '../lib/auth';
import { formatDate, formatDateTime, money } from '../lib/format';
import { useI18n, useT } from '../lib/i18n';
import { printPage } from '../lib/export';
import { useMethodLabel } from './FeesPage';

const M = {
  en: {
    back: 'Back to fees', official: 'Official receipt', receiptNo: 'Receipt no.', date: 'Date paid', receivedFrom: 'Received from',
    admission: 'Admission no.', class: 'Class', for: 'Payment for', amountPaid: 'Amount paid', method: 'Payment method', reference: 'Reference',
    recordedBy: 'Recorded by', invoiceTotal: 'Invoice total', balanceAfter: 'Balance after this payment', fullyPaid: 'Fully paid',
    generated: 'This receipt was generated by EduLearn on {date}. Payments are recorded by the school bursar.',
    signature: 'Bursar’s signature & stamp', tel: 'Tel.', email: 'Email', notFound: 'This receipt could not be found',
  },
  sw: {
    back: 'Rudi kwenye ada', official: 'Stakabadhi rasmi', receiptNo: 'Namba ya stakabadhi', date: 'Tarehe ya malipo', receivedFrom: 'Imepokelewa kutoka kwa',
    admission: 'Namba ya usajili', class: 'Darasa', for: 'Malipo ya', amountPaid: 'Kiasi kilicholipwa', method: 'Njia ya malipo', reference: 'Kumbukumbu',
    recordedBy: 'Imerekodiwa na', invoiceTotal: 'Jumla ya ankara', balanceAfter: 'Salio baada ya malipo haya', fullyPaid: 'Imelipwa yote',
    generated: 'Stakabadhi hii imetolewa na EduLearn tarehe {date}. Malipo hurekodiwa na mhasibu wa shule.',
    signature: 'Sahihi na muhuri wa mhasibu', tel: 'Simu', email: 'Barua pepe', notFound: 'Stakabadhi hii haikupatikana',
  },
};

export function ReceiptPage() {
  const t = useT(M);
  const { t: tc } = useI18n();
  const user = useUser();
  const navigate = useNavigate();
  const methodLabel = useMethodLabel();
  const { paymentId } = useParams();
  const q = useQuery({
    queryKey: ['receipt', paymentId],
    queryFn: () => api.get<Receipt>(`/fees/payments/${paymentId}/receipt`),
    enabled: !!paymentId,
  });

  if (q.isLoading) return <CardSkeleton rows={10} />;
  if (q.error || !q.data) return <ErrorState error={q.error ?? new Error(t('notFound'))} onRetry={q.refetch} />;
  const { school, payment, invoice, balanceAfter } = q.data;

  return (
    <>
      <div className="row between row-wrap no-print mb-3">
        <Button variant="ghost" icon={<ArrowLeft size={17} />} onClick={() => (window.history.length > 1 ? navigate(-1) : navigate('/fees'))}>
          {t('back')}
        </Button>
        <Button variant="primary" icon={<Printer size={17} />} onClick={printPage}>{tc('printPdf')}</Button>
      </div>

      <article className="document" aria-labelledby="receipt-title">
        <header className="doc-head">
          {school.logoUrl ? (
            <img className="doc-logo" src={school.logoUrl} alt="" />
          ) : (
            <span className="doc-logo" style={{ display: 'grid', placeItems: 'center', background: '#0f2547', color: '#fff' }} aria-hidden>
              <GraduationCap size={34} />
            </span>
          )}
          <div style={{ flex: 1 }}>
            <h1 style={{ fontSize: '1.4rem', margin: 0 }}>{school.name}</h1>
            {school.motto && <div className="muted small" style={{ fontStyle: 'italic' }}>{school.motto}</div>}
            <div className="muted small">
              {[school.address, school.phone && `${t('tel')} ${school.phone}`, school.email && `${t('email')} ${school.email}`].filter(Boolean).join(' · ')}
            </div>
          </div>
          <div style={{ textAlign: 'right' }}>
            <h2 id="receipt-title" style={{ fontSize: '1.1rem', margin: 0, textTransform: 'uppercase', letterSpacing: '0.04em' }}>{t('official')}</h2>
            <div className="small muted">Stakabadhi rasmi</div>
            <div className="mono bold" style={{ fontSize: '1.05rem', marginTop: 6 }}>{payment.receiptNo}</div>
          </div>
        </header>

        <table aria-label={t('official')}>
          <tbody>
            <tr><th scope="row" style={{ width: '38%' }}>{t('receiptNo')}</th><td className="mono">{payment.receiptNo}</td></tr>
            <tr><th scope="row">{t('date')}</th><td>{formatDate(payment.paidOn, { day: 'numeric', month: 'long', year: 'numeric' })}</td></tr>
            <tr><th scope="row">{t('receivedFrom')}</th><td><strong>{invoice.studentName}</strong></td></tr>
            <tr><th scope="row">{t('admission')}</th><td>{invoice.admissionNo}</td></tr>
            <tr><th scope="row">{t('class')}</th><td>{invoice.className ?? '—'}</td></tr>
            <tr><th scope="row">{t('for')}</th><td>{invoice.title}</td></tr>
            <tr>
              <th scope="row">{t('amountPaid')}</th>
              <td><strong style={{ fontSize: '1.25rem' }}>{money(payment.amount)}</strong></td>
            </tr>
            <tr><th scope="row">{t('method')}</th><td>{methodLabel(payment.method)}</td></tr>
            <tr><th scope="row">{t('reference')}</th><td className="mono">{payment.reference ?? '—'}</td></tr>
            <tr><th scope="row">{t('recordedBy')}</th><td>{payment.recordedByName ?? '—'}</td></tr>
            <tr><th scope="row">{t('invoiceTotal')}</th><td>{money(invoice.amount)}</td></tr>
            <tr>
              <th scope="row">{t('balanceAfter')}</th>
              <td><strong>{balanceAfter > 0 ? money(balanceAfter) : `${money(0)} · ${t('fullyPaid')}`}</strong></td>
            </tr>
          </tbody>
        </table>

        <div className="row between" style={{ marginTop: 48, alignItems: 'flex-end', gap: 24, flexWrap: 'wrap' }}>
          <p className="muted small" style={{ maxWidth: 420, margin: 0 }}>{t('generated', { date: formatDateTime(new Date().toISOString()) })}</p>
          <div style={{ textAlign: 'center', minWidth: 220 }}>
            <div style={{ borderTop: '1px solid #555', paddingTop: 6 }} className="small muted">{t('signature')}</div>
          </div>
        </div>
      </article>

      {user.role === 'admin' && (
        <p className="small muted no-print mt-2" style={{ textAlign: 'center' }}>
          <Link to={`/fees?studentId=${invoice.studentId}`}>{invoice.studentName}</Link>
        </p>
      )}
    </>
  );
}
